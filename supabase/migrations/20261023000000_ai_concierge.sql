create table public.ai_usage (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users (id) on delete set null,
  provider_id uuid references public.providers (id) on delete set null,
  feature text not null check (feature in (
    'chat', 'profile_draft', 'weekly_summary', 'document_embedding'
  )),
  model text not null default '',
  status text not null default 'started' check (status in ('started', 'finished', 'failed')),
  tokens_in integer not null default 0 check (tokens_in >= 0),
  tokens_out integer not null default 0 check (tokens_out >= 0),
  -- Millionths of a US dollar. One chat answer costs a fraction of a cent, so integer cents would
  -- round every row to zero; integer micro-dollars keep money exact without floating point.
  cost_micros bigint not null default 0 check (cost_micros >= 0),
  created_at timestamptz not null default now()
);
create index ai_usage_user_created_idx on public.ai_usage (user_id, created_at);
create index ai_usage_created_idx on public.ai_usage (created_at);

