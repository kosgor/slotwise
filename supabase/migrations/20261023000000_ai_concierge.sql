-- lib/ai/limits.ts: MAX_DOCUMENTS = 5 per provider. Each document costs embeddings, so the cap is
-- in the database, like the Free plan's service limit.
create function private.enforce_document_limit()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if (select count(*) from public.provider_documents where provider_id = new.provider_id) > 5 then
    raise exception 'document_limit';
  end if;
  return null;
end;
$$;
revoke execute on function private.enforce_document_limit() from public;

create trigger provider_documents_limit
  after insert on public.provider_documents
  for each row execute function private.enforce_document_limit();

-- Chunks with embeddings. gemini-embedding-2 reduced to 768 dimensions (lib/ai/models.ts).
create table public.document_chunks (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.provider_documents (id) on delete cascade,
  provider_id uuid not null references public.providers (id) on delete cascade,
  chunk_index integer not null check (chunk_index >= 0),
  content text not null check (char_length(content) between 1 and 4000),
  embedding extensions.vector(768) not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (document_id, chunk_index)
);
-- Every search is filtered by provider: an exact scan over one provider's few hundred chunks is
-- fast and always correct. An approximate index (HNSW) pays off only with far more data.
create index document_chunks_provider_idx on public.document_chunks (provider_id);

alter table public.document_chunks enable row level security;

create policy "Owners read their chunks"
  on public.document_chunks for select to authenticated
  using ((select private.owns_provider(provider_id)));

grant select on public.document_chunks to authenticated;
grant select, insert, update, delete on public.document_chunks to service_role;

-- Semantic search inside one provider's ready documents. Clients may search the documents of an
-- approved provider (that is the point: "what is Anna's cancellation policy?"); owners may also
-- search their own while the profile is still in review. Only chunks at or above the similarity
-- threshold come back, so "nothing relevant" is an empty result, not the closest noise.
create function public.match_document_chunks(
  p_provider_id uuid,
  p_embedding extensions.vector(768),
  p_threshold double precision default 0.6,
  p_limit integer default 4
) returns table (
  id uuid,
  document_id uuid,
  document_title text,
  content text,
  similarity double precision
)
language sql stable security definer set search_path = ''
as $$
  select c.id, c.document_id, d.title, c.content,
         1 - (c.embedding operator(extensions.<=>) p_embedding) as similarity
  from public.document_chunks c
  join public.provider_documents d on d.id = c.document_id and d.status = 'ready'
  join public.providers p on p.id = c.provider_id
  where c.provider_id = p_provider_id
    and (p.status = 'approved' or p.user_id = (select auth.uid()))
    and 1 - (c.embedding operator(extensions.<=>) p_embedding) >= p_threshold
  order by c.embedding operator(extensions.<=>) p_embedding
  limit least(greatest(p_limit, 1), 8);
$$;
revoke execute on function public.match_document_chunks(uuid, extensions.vector, double precision, integer) from public, anon;
grant execute on function public.match_document_chunks(uuid, extensions.vector, double precision, integer) to authenticated;

-- The processing job's result in one transaction: old chunks out, new chunks in, status ready.
-- p_chunks: [{ "content": "...", "embedding": [0.1, ...], "metadata": {...} }, ...]
create function public.replace_document_chunks(p_document_id uuid, p_chunks jsonb)
returns integer
language plpgsql security definer set search_path = ''
as $$
declare
  v_provider uuid;
  v_count integer;
begin
  select provider_id into v_provider
  from public.provider_documents where id = p_document_id for update;
  if not found then
    raise exception 'document_not_found';
  end if;

  delete from public.document_chunks where document_id = p_document_id;
  insert into public.document_chunks (document_id, provider_id, chunk_index, content, embedding, metadata)
  select p_document_id, v_provider, (t.ord - 1)::integer, t.c ->> 'content',
         (t.c ->> 'embedding')::extensions.vector, coalesce(t.c -> 'metadata', '{}'::jsonb)
  from jsonb_array_elements(p_chunks) with ordinality as t(c, ord);
  get diagnostics v_count = row_count;

  update public.provider_documents
  set status = 'ready', chunk_count = v_count, error = null
  where id = p_document_id;
  return v_count;
end;
$$;
revoke execute on function public.replace_document_chunks(uuid, jsonb) from public, anon, authenticated;
grant execute on function public.replace_document_chunks(uuid, jsonb) to service_role;

-- Private bucket for the files. Paths start with the provider id: "<provider_id>/<file>".
-- Conditional: the storage schema exists on Supabase; PGlite tests create a stand-in.
create function private.owns_document_path(p_name text) returns boolean
language sql stable security definer set search_path = ''
as $$
  select split_part(p_name, '/', 1) ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
     and private.owns_provider(split_part(p_name, '/', 1)::uuid);
$$;
revoke execute on function private.owns_document_path(text) from public;
grant execute on function private.owns_document_path(text) to authenticated;

