-- Daily AI requests for a user: Free 30, Pro (a provider with an active Pro plan) 150.
-- lib/ai/limits.ts: DAILY_AI_REQUESTS.
create function private.daily_ai_limit(p_user_id uuid) returns integer
language sql stable security definer set search_path = ''
as $$
  select case when exists (
    select 1 from public.providers p
    where p.user_id = p_user_id and private.provider_plan(p.id) = 'pro'
  ) then 150 else 30 end;
$$;
revoke execute on function private.daily_ai_limit(uuid) from public;

-- Counts one AI request for the signed-in user, or refuses it. Checks, in order:
--   ai_rate_limited — more than 6 requests in the last minute (lib/ai/limits.ts: RATE_LIMIT_PER_MINUTE)
--   ai_daily_limit  — the daily allowance (UTC day) is used up
-- Returns the ai_usage row id; the server fills in tokens and cost when the answer is done.
-- An advisory lock per user makes check-and-insert atomic: parallel requests wait for each other.
create function public.claim_ai_request(p_feature text, p_provider_id uuid default null)
returns uuid
language plpgsql security definer set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_id uuid;
begin
  if v_user is null then
    raise exception 'not_authenticated';
  end if;
  if p_feature not in ('chat', 'profile_draft', 'weekly_summary') then
    raise exception 'invalid_feature';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('ai_usage:' || v_user::text, 0));

  if (
    select count(*) from public.ai_usage
    where user_id = v_user and created_at > now() - interval '1 minute'
  ) >= 6 then
    raise exception 'ai_rate_limited';
  end if;

  if (
    select count(*) from public.ai_usage
    where user_id = v_user
      and status <> 'failed'
      and feature <> 'document_embedding'
      and created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc'
  ) >= private.daily_ai_limit(v_user) then
    raise exception 'ai_daily_limit';
  end if;

  insert into public.ai_usage (user_id, provider_id, feature)
  values (v_user, p_provider_id, p_feature)
  returning id into v_id;
  return v_id;
end;
$$;
revoke execute on function public.claim_ai_request(text, uuid) from public, anon;
grant execute on function public.claim_ai_request(text, uuid) to authenticated;

-- What the chat shows under the input: "12 of 30 AI requests left today".
create function public.ai_requests_left() returns integer
language sql stable security definer set search_path = ''
as $$
  select greatest(private.daily_ai_limit((select auth.uid())) - (
    select count(*)::integer from public.ai_usage
    where user_id = (select auth.uid())
      and status <> 'failed'
      and feature <> 'document_embedding'
      and created_at >= date_trunc('day', now() at time zone 'utc') at time zone 'utc'
  ), 0);
$$;
revoke execute on function public.ai_requests_left() from public, anon;
grant execute on function public.ai_requests_left() to authenticated;

