-- Stage 4: AI concierge — chat history, provider documents for RAG, AI usage and limits.
--
-- Access model (same as bookings, docs/decisions/0011):
-- * The chat runs as the signed-in user. Tools call the Data API with the user's session, so RLS
--   decides what the model can see — a prompt cannot widen it.
-- * Chat history belongs to the user: they read and write only their own conversations.
-- * Documents: providers upload their own; chunks and embeddings are written only by the
--   background job (service_role). Clients search them through match_document_chunks().
-- * ai_usage is server bookkeeping: users read their own rows, never write them. The limit check
--   and the row that counts the request are one function (claim_ai_request), so two parallel
--   requests cannot both slip under the limit.
--
-- Limits are mirrored in lib/ai/limits.ts; tests/rls checks they agree.

create extension if not exists vector with schema extensions;

-- ---------------------------------------------------------------------------------------------
-- Conversations and messages
-- ---------------------------------------------------------------------------------------------

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  -- Set when the chat was started on a provider's page: the assistant answers about them.
  provider_id uuid references public.providers (id) on delete cascade,
  title text not null default '' check (char_length(title) <= 120),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index conversations_user_idx on public.conversations (user_id, updated_at desc);

create trigger conversations_set_updated_at
  before update on public.conversations
  for each row execute function public.set_updated_at();

-- One row per UI message (AI SDK UIMessage). `parts` keeps text, tool calls and tool results in
-- order, exactly as the chat renders them — the plan's content + tool_calls in one column.
create table public.messages (
  conversation_id uuid not null references public.conversations (id) on delete cascade,
  -- Generated by the AI SDK (client for user messages, server for answers), not a uuid.
  id text not null check (char_length(id) between 1 and 64),
  role text not null check (role in ('user', 'assistant')),
  parts jsonb not null check (jsonb_typeof(parts) = 'array'),
  created_at timestamptz not null default now(),
  -- Ids are unique per conversation, so one user's ids can never collide with another's rows.
  primary key (conversation_id, id)
);
create index messages_conversation_created_idx on public.messages (conversation_id, created_at);

create function private.owns_conversation(p_conversation_id uuid) returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.conversations where id = p_conversation_id and user_id = (select auth.uid())
  );
$$;
revoke execute on function private.owns_conversation(uuid) from public;
grant execute on function private.owns_conversation(uuid) to authenticated;

